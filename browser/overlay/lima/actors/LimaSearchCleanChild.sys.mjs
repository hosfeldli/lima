/** The watch page for a Shorts URL, or null. */
export function shortsWatchURL(url) {
  try {
    const parsed = new URL(url);
    const id = /^\/shorts\/([\w-]{6,20})\/?$/.exec(parsed.pathname)?.[1];
    return /(^|\.)youtube\.com$/.test(parsed.hostname) && id ? `https://www.youtube.com/watch?v=${id}` : null;
  } catch { return null; }
}

export function engineFor(url) {
  let host, path;
  try { ({ hostname: host, pathname: path } = new URL(url)); } catch { return null; }
  if (/(^|\.)youtube\.com$/.test(host)) return "youtube";
  if (/(^|\.)google\.[a-z.]+$/.test(host) && path === "/search") return "google";
  if (/(^|\.)bing\.com$/.test(host) && path === "/search") return "bing";
  if (/(^|\.)duckduckgo\.com$/.test(host) && path === "/") return "duckduckgo";
  if (/(^|\.)search\.yahoo\.com$/.test(host) && path.startsWith("/search")) return "yahoo";
  if (host === "search.brave.com" && path === "/search") return "brave";
  return null;
}

export const ENGINES = ["google", "bing", "duckduckgo", "yahoo", "brave"];

/** The switches in Settings → Search. `engines`: where result filters apply. */
export function settings() {
  const listed = Services.prefs.getStringPref("lima.search.cleanEngines", ENGINES.join(","));
  return {
    ai: Services.prefs.getBoolPref("lima.search.hideAI", true),
    ads: Services.prefs.getBoolPref("lima.search.hideAds", true),
    shorts: Services.prefs.getBoolPref("lima.youtube.hideShorts", true),
    engines: new Set(listed.split(",").map(name => name.trim()).filter(Boolean)),
  };
}

// The results themselves. A rule never hides an element that holds these, so
// a selector or heading that matches too much hides nothing instead of the page.
const RESULTS = "#rso, #search, #center_col, #rcnt, #b_results, #b_content, [data-testid='mainline'], .react-results--main, #web, #results, main";
const ORGANIC = "a h3, li.b_algo, [data-testid='result'], article[data-nrn='result'], #web > ol > li, .snippet[data-type='web']";

/** True when hiding `element` can't take real results with it. */
export function safeToHide(element) {
  if (!element || ["HTML", "BODY", "MAIN"].includes(element.tagName) || element.matches(RESULTS)) return false;
  if (element.querySelector(RESULTS)) return false;
  return element.querySelectorAll(ORGANIC).length <= 1;
}

export function stylesheet(engine, { ai, ads, shorts }) {
  if (engine === "youtube") return shorts ? `${SHORTS.join(",\n")} { display: none !important; }\n` : "";
  const rules = RULES[engine];
  // Hidden before first paint, except anything that holds the results.
  const guard = `:not(:has(${RESULTS}))`;
  const selectors = [...(ads ? rules.ads : []), ...(ai ? rules.ai : [])].map(selector => selector + guard);
  return `${selectors.length ? `${selectors.join(",\n")} { display: none !important; }\n` : ""}[data-lima-hidden] { display: none !important; }\n`;
}

export class LimaSearchCleanChild extends JSWindowActorChild {
  handleEvent(event) {
    const doc = this.document;
    const engine = engineFor(doc?.location?.href);
    if (!engine) return;
    const choice = settings();
    if (engine === "youtube") { this.youtube(event, choice); return; }
    if ((!choice.ai && !choice.ads) || !choice.engines.has(engine)) return;
    if (event.type === "DOMDocElementInserted") {
      // Before first paint, so hidden blocks never flash in.
      const style = doc.createElement("style");
      style.textContent = stylesheet(engine, choice);
      (doc.head ?? doc.documentElement).append(style);
      return;
    }
    if (event.type === "DOMContentLoaded" && choice.ai) this.watchHeadings(engine);
  }

  youtube(event, { shorts }) {
    if (!shorts) return;
    const doc = this.document;
    const win = this.contentWindow;
    const redirect = () => {
      const watch = shortsWatchURL(win.location.href);
      if (watch) win.location.replace(watch);
    };
    if (event.type === "DOMDocElementInserted") {
      redirect();
      const style = doc.createElement("style");
      style.textContent = stylesheet("youtube", { shorts });
      (doc.head ?? doc.documentElement).append(style);
      return;
    }
    if (event.type === "DOMContentLoaded" && !this.watching) {
      // YouTube navigates in-page; catch Shorts opened from its own links.
      this.watching = true;
      doc.addEventListener("yt-navigate-finish", redirect, true, true);
      win.addEventListener("popstate", redirect);
      doc.addEventListener("click", clicked => {
        const link = clicked.target?.closest?.("a[href^='/shorts/']");
        const watch = link && shortsWatchURL(new URL(link.getAttribute("href"), win.location.href).href);
        if (!watch) return;
        clicked.preventDefault();
        clicked.stopImmediatePropagation();
        win.location.assign(watch);
      }, true);
    }
  }

  /** Hides the result block around a heading that names an AI answer.
   * Only real headings count (not tab labels or links such as Google's "AI
   * Mode" tab), and only a block that holds no real results is hidden. */
  watchHeadings(engine) {
    const doc = this.document;
    const { aiHeadings, container } = RULES[engine];
    const sweep = () => {
      for (const heading of doc.querySelectorAll("h1, h2, h3, [role='heading']")) {
        const text = heading.textContent?.trim();
        if (!text || text.length > 60 || !aiHeadings.some(pattern => pattern.test(text))) continue;
        if (heading.closest("a, nav, [role='navigation'], [role='tablist'], header")) continue;
        const block = heading.closest(container);
        if (block && !block.hasAttribute("data-lima-hidden") && safeToHide(block)) block.setAttribute("data-lima-hidden", "ai");
      }
    };
    sweep();
    let pending = false;
    const observer = new this.contentWindow.MutationObserver(() => {
      if (pending) return;
      pending = true;
      this.contentWindow.requestAnimationFrame(() => { pending = false; sweep(); });
    });
    observer.observe(doc.body ?? doc.documentElement, { childList: true, subtree: true });
    // Results settle within seconds; stop watching after that.
    this.contentWindow.setTimeout(() => observer.disconnect(), 15000);
  }
}
