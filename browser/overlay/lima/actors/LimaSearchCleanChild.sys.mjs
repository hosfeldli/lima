/* Cleaner pages, per the Settings → General → Browsing switches:
 * - search results without AI answers or sponsored results
 *   (`lima.search.hideAI`, `lima.search.hideAds`) on Google, Bing,
 *   DuckDuckGo, Yahoo and Brave result pages;
 * - YouTube without Shorts (`lima.youtube.hideShorts`): shelves, the Shorts
 *   tab and entries are hidden, and a /shorts/ link plays as a normal video.
 * It only hides elements (and rewrites a Shorts URL to its watch page); it
 * never changes queries or results and never sends anything anywhere. */

